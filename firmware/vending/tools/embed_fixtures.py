"""Embed test/fixtures/*.json as C++ string constants in fixtures.h (run by hand, commit the output)."""

from pathlib import Path

root = Path(__file__).resolve().parent.parent / "test" / "fixtures"
lines = ["// Generated by tools/embed_fixtures.py - do not edit.", "#pragma once", ""]
for path in sorted(root.glob("*.json")):
    lines.append(
        f'constexpr const char* kFixture_{path.stem} = R"JSON({path.read_text().strip()})JSON";'
    )
(root / "fixtures.h").write_text("\n".join(lines) + "\n", newline="\n")
